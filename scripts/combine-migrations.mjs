#!/usr/bin/env node
// Concatenates supabase/migrations/*.sql into supabase/all_migrations.sql so it can be pasted into the Supabase SQL Editor in one go.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './env.mjs';

export function combined() {
  const dir = join(root, 'supabase/migrations');
  const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  return `-- MailBlaster AI: all migrations in order (generated by scripts/combine-migrations.mjs - do not edit)\n-- Paste into Supabase -> SQL Editor -> New query -> Run. Safe to run once on an empty project.\n\n` +
    files.map((f) => `-- ===== ${f} =====\n${readFileSync(join(dir, f), 'utf8')}`).join('\n\n');
}
if (process.argv[1] && process.argv[1].endsWith('combine-migrations.mjs')) {
  writeFileSync(join(root, 'supabase/all_migrations.sql'), combined());
  console.log('wrote supabase/all_migrations.sql');
}
